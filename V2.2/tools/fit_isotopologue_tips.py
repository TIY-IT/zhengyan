"""Fit per-isotopologue TIPS-2021 partition sums and write isotopologue_data.py.

Source data: HITRANonline molparam / q<global_id>.txt (1 K grid).  Run with
network access whenever isotopologues need to be added:

    python tools/fit_isotopologue_tips.py --out isotopologue_data.py

The fit convention is identical to the one used for the main isotopologues in
reproduce_lbl_twostream.py: a 15-term Chebyshev series for log Q(T) on
z = 2 (T - 296) / (1800 - 296) - 1.
"""
from __future__ import annotations

import argparse
import re
import urllib.request
from pathlib import Path

import numpy as np

# (species, HITRAN molecule id, local isotopologue id, HITRAN global id, AFGL code, molar mass g/mol)
# Verified against https://hitran.org/docs/iso-meta/ (molparam).
ISOTOPOLOGUES = [
    ("H2O", 1, 1, 1, "161", 18.010565), ("H2O", 1, 2, 2, "181", 20.014811),
    ("H2O", 1, 3, 3, "171", 19.014780), ("H2O", 1, 4, 4, "162", 19.016740),
    ("H2O", 1, 5, 5, "182", 21.020985), ("H2O", 1, 6, 6, "172", 20.020956),
    ("H2O", 1, 7, 129, "262", 20.022915),
    ("CO", 5, 1, 26, "26", 27.994915), ("CO", 5, 2, 27, "36", 28.998270),
    ("CO", 5, 3, 28, "28", 29.999161), ("CO", 5, 4, 29, "27", 28.999130),
    ("CO", 5, 5, 30, "38", 31.002516), ("CO", 5, 6, 31, "37", 30.002485),
    ("CH4", 6, 1, 32, "211", 16.031300), ("CH4", 6, 2, 33, "311", 17.034655),
    ("CH4", 6, 3, 34, "212", 17.037475), ("CH4", 6, 4, 35, "312", 18.040830),
    ("NH3", 11, 1, 45, "4111", 17.026549), ("NH3", 11, 2, 46, "5111", 18.023583),
]
T_MIN, T_MAX, DEGREE = 296.0, 1800.0, 14


def fetch_q(global_id: int, cache: Path | None) -> np.ndarray:
    path = cache / f"q{global_id}.txt" if cache else None
    if path and path.is_file():
        text = path.read_text()
    else:
        with urllib.request.urlopen(f"https://hitran.org/data/Q/q{global_id}.txt", timeout=60) as r:
            text = r.read().decode()
        if path:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    rows = [tuple(map(float, line.split()[:2])) for line in text.splitlines() if line.strip()]
    return np.asarray(rows)


def fit(table: np.ndarray) -> tuple[np.ndarray, float]:
    t = table[:, 0]
    keep = (t >= T_MIN) & (t <= T_MAX)
    t, q = t[keep], table[keep, 1]
    z = 2.0 * (t - T_MIN) / (T_MAX - T_MIN) - 1.0
    coef = np.polynomial.chebyshev.chebfit(z, np.log(q), DEGREE)
    err = np.max(np.abs(np.polynomial.chebyshev.chebval(z, coef) - np.log(q)))
    return coef, float(err)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "isotopologue_data.py")
    ap.add_argument("--cache", type=Path, default=None, help="directory holding q<id>.txt files")
    args = ap.parse_args()
    lines = [
        '"""Per-isotopologue masses and TIPS-2021 log Q Chebyshev fits (auto-generated).',
        "",
        "Generated by tools/fit_isotopologue_tips.py from HITRANonline molparam and",
        "q<global id>.txt.  Do not edit by hand.  z = 2(T-296)/(1800-296)-1.",
        '"""',
        "import numpy as np",
        "",
        "# (species, local isotopologue id) -> (AFGL code, molar mass in amu, max |dlogQ| of the fit)",
        "ISOTOPOLOGUE_INFO = {",
    ]
    coefs = {}
    for species, _, local, gid, afgl, mass in ISOTOPOLOGUES:
        c, err = fit(fetch_q(gid, args.cache))
        coefs[(species, local)] = c
        lines.append(f'    ("{species}", {local}): ("{afgl}", {mass!r}, {err:.2e}),')
    lines += ["}", "", "ISOTOPOLOGUE_LOG_Q_CHEBYSHEV = {"]
    for (species, local), c in coefs.items():
        body = ", ".join(repr(float(x)) for x in c)
        lines.append(f'    ("{species}", {local}): np.asarray([{body}]),')
    lines.append("}")
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out} ({len(coefs)} isotopologues)")


if __name__ == "__main__":
    main()
